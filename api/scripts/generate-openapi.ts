const yamlOutput = HEADER_COMMENT + stringify(buildClientOpenApiDocument(), { lineWidth: 100 });
const isCheckMode = process.argv.includes('--check');

if (isCheckMode) {
  const existing = readFileSync(OUTPUT_PATH, 'utf8').replace(/\r\n/g, '\n');
  if (existing !== yamlOutput) {
    console.error(
      'docs/api/openapi.client.yaml is out of sync with api/scripts/generate-openapi.ts. Run `npm run openapi:generate --prefix api`.',
    );
    process.exit(1);
  }
  console.log('OpenAPI client spec is up to date.');
} else {
  writeFileSync(OUTPUT_PATH, yamlOutput, 'utf8');
  console.log(`Wrote ${OUTPUT_PATH}`);
}
