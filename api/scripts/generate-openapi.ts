const HEADER_COMMENT =
  '# Generated by `npm run openapi:generate --prefix api` from Zod schemas. Do not hand-edit.\n';

function zodToOpenApiSchema(schema: z.ZodType): Record<string, unknown> {
  const jsonSchema = z.toJSONSchema(schema, { target: 'openapi-3.0' }) as Record<string, unknown>;
  delete jsonSchema.$schema;
  return jsonSchema;
}

function errorResponseRef(refName: string) {
  return { $ref: `#/components/responses/${refName}` };
}

function notFoundResponse(
  resource: string,
  description = 'Resource not found or caller lacks access',
) {
  return {
    description,
    content: {
      'application/json': {
        schema: { $ref: '#/components/schemas/ErrorResponse' },
        example: { error: { code: 'NOT_FOUND', details: [{ resource }] } },
      },
    },
  };
}

function jsonContent(schemaRef: string, example?: Record<string, unknown>) {
  return {
    'application/json': {
      schema: { $ref: `#/components/schemas/${schemaRef}` },
      ...(example ? { example } : {}),
    },
  };
}

function inlineErrorContent(code: string) {
  return {
    'application/json': {
      schema: { $ref: '#/components/schemas/ErrorResponse' },
      example: { error: { code } },
    },
  };
}

function multiErrorResponse(
  description: string,
  examples: Record<string, { summary: string; value: Record<string, unknown> }>,
) {
  return {
    description,
    content: {
      'application/json': {
        schema: { $ref: '#/components/schemas/ErrorResponse' },
        examples,
      },
    },
  };
}

